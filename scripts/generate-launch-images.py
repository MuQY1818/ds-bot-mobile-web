#!/usr/bin/env python3
"""Generate the server-only iPhone launch-image module; requires Pillow >= 10.1.

Run with a Python environment containing Pillow. The output embeds PNG bytes in
one server module, never in HTML or the browser bundle. These are static iOS
startup images; the drawn loading ring is not an animated progress indicator.

Apple startup-image reference:
https://developer.apple.com/library/archive/documentation/AppleApplications/Reference/SafariWebContent/ConfiguringWebApplications/ConfiguringWebApplications.html
Media/device sizing reference:
https://vite-pwa-org.netlify.app/assets-generator/cli.html#apple-splash-screens
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError as error:
    raise SystemExit("This development script requires Pillow >= 10.1.") from error


# CSS screen width, CSS screen height, device pixel ratio; portrait only.
SCREENS = (
    (430, 932, 3),
    (390, 844, 3),
    (393, 852, 3),
    (402, 874, 3),
    (440, 956, 3),
    (428, 926, 3),
    (414, 896, 2),
    (414, 896, 3),
    (375, 812, 3),
    (375, 667, 2),
)
THEMES = {
    "light": {"background": "#ffffff", "ink": "#202020", "ring": "#e9e9e9"},
    "dark": {"background": "#141414", "ink": "#e5e5e5", "ring": "#343434"},
}

MODULE = r'''// Generated by scripts/generate-launch-images.py. Do not hand-edit image data.
// Server only: import from index.mjs, never from client.mjs or web-startup.mjs.
// iOS displays these as static OS launch images. The ring does not animate.
import {Buffer} from 'node:buffer'

const entries=__IMAGES__

export const WEB_LAUNCH_IMAGES=Object.freeze(entries.map(({base64,...image})=>Object.freeze(image)))

export function renderWebLaunch(html){
  if(html.includes('data-dsm-launch="v1"'))return html
  const links=WEB_LAUNCH_IMAGES.map(image=>`<link rel="apple-touch-startup-image" data-dsm-launch="v1" href="${image.path}" media="${image.media}">`).join('')
  return html.replace(/<head(?:\s[^>]*)?>/i,open=>open+links)
}

export function applyWebLaunch(ctx){
  if(typeof ctx.webServer?.tapIndex!=='function'||typeof ctx.webServer?.register!=='function')return
  ctx.effect(()=>{
    const disposers=[]
    try{
      for(const image of entries){
        let bytes
        disposers.push(ctx.webServer.register({kind:'exact',path:image.path,handler(request,response){
          const headers={'content-type':'image/png','cache-control':'public, max-age=31536000, immutable','x-content-type-options':'nosniff'}
          if(!['GET','HEAD'].includes(request.method)){
            response.writeHead(405,{...headers,allow:'GET, HEAD'});response.end();return
          }
          bytes??=Buffer.from(image.base64,'base64')
          response.writeHead(200,{...headers,'content-length':String(bytes.length)})
          response.end(request.method==='HEAD'?undefined:bytes)
        }}))
      }
      disposers.push(ctx.webServer.tapIndex(renderWebLaunch))
    }catch(error){
      for(const dispose of disposers.reverse())dispose()
      throw error
    }
    return()=>{for(const dispose of disposers.reverse())dispose()}
  })
}
'''


def png_image(width: int, height: int, ratio: int, theme: str) -> bytes:
    palette = THEMES[theme]
    image = Image.new("RGB", (width * ratio, height * ratio), palette["background"])
    # Supersample only the small central artwork, keeping full-screen rendering
    # inexpensive even for 1320 x 2868 output. Pillow's bundled Latin font avoids
    # machine-specific font paths and contains the exact product label we draw.
    scale = ratio * 3
    tile = Image.new("RGB", (200 * scale, 160 * scale), palette["background"])
    draw = ImageDraw.Draw(tile)
    stroke = round(2.5 * scale)
    ring = (83 * scale, 35 * scale, 117 * scale, 69 * scale)
    draw.ellipse(ring, outline=palette["ring"], width=stroke)
    draw.arc(ring, 255, 335, fill=palette["ink"], width=stroke)
    draw.text((100 * scale, 108 * scale), "DS Bot", anchor="mm",
              font=ImageFont.load_default(size=28 * scale), fill=palette["ink"])
    tile = tile.resize((200 * ratio, 160 * ratio), Image.Resampling.LANCZOS)
    image.paste(tile, ((image.width - tile.width) // 2, (image.height - tile.height) // 2))
    # Every theme is neutral grayscale. Keep all antialiasing shades while
    # avoiding three duplicate color channels in the public PNGs.
    image = image.convert("L")
    output = io.BytesIO()
    image.save(output, format="PNG", optimize=True, compress_level=9)
    return output.getvalue()


def main() -> None:
    default = Path(__file__).resolve().parents[1] / "mobile-web-prototype/plugin/web-launch.mjs"
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=default, help="Generated server module path")
    args = parser.parse_args()
    entries = []
    total = 0
    for width, height, ratio in SCREENS:
        for theme in THEMES:
            data = png_image(width, height, ratio, theme)
            total += len(data)
            digest = hashlib.sha256(data).hexdigest()[:16]
            filename = f"iphone-{width}x{height}-{ratio}x-{theme}-{digest}.png"
            media = (f"screen and (device-width: {width}px) and (device-height: {height}px) "
                     f"and (-webkit-device-pixel-ratio: {ratio}) and (orientation: portrait) "
                     f"and (prefers-color-scheme: {theme})")
            entries.append({"width": width, "height": height, "ratio": ratio,
                            "theme": theme, "path": f"/ds-bot-mobile-web-launch/v1/{filename}",
                            "media": media, "base64": base64.b64encode(data).decode("ascii")})
    module = MODULE.replace("__IMAGES__", json.dumps(entries, ensure_ascii=True, separators=(",", ":")))
    args.output.write_text(module, encoding="utf-8")
    print(f"Generated {len(entries)} static launch PNGs ({total:,} bytes) in {args.output.name}")


if __name__ == "__main__":
    main()
