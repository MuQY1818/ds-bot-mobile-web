import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
const root = new URL('../', import.meta.url)
const artifacts = new URL('artifacts/', root)
const source = JSON.parse(await readFile(new URL('package.json', root), 'utf8'))
const plugin = JSON.parse(await readFile(new URL('mobile-web-prototype/plugin/package.json', root), 'utf8'))
if (source.version !== plugin.version) throw new Error('Root and plugin versions must match before packaging')
const changes = () => execFileSync('git', ['status', '--porcelain', '--untracked-files=normal'], { cwd: root, encoding: 'utf8' }).trim()
if (changes()) throw new Error('Commit source, tests and documentation before packaging a release')
execFileSync('npm', ['run', 'build'], { cwd: root, stdio: 'inherit' })
if (changes()) throw new Error('Generated client differs from the committed source; commit the rebuild first')
const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim()
await mkdir(artifacts, { recursive: true })
const output = execFileSync('npm', ['pack', './mobile-web-prototype/plugin', '--ignore-scripts', '--json', '--pack-destination', artifacts.pathname], { cwd: root, encoding: 'utf8' })
const [result] = JSON.parse(output)
const expected = ['package.json', ...plugin.files].sort()
const actual = result.files.map(file => file.path).sort()
if (JSON.stringify(actual) !== JSON.stringify(expected)) throw new Error('Package members differ from the explicit release allowlist')
const sha256 = createHash('sha256').update(await readFile(new URL(result.filename, artifacts))).digest('hex')
if (changes() || execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim() !== commit) throw new Error('Source changed while packaging; do not publish this archive')
const release = { name: result.name, version: result.version, commit, dirty: false, filename: result.filename, sha256 }
await writeFile(new URL('SHA256SUMS', artifacts), `${sha256}  ${result.filename}\n`)
for (const filename of ['release.json', `release-${result.version}.json`]) await writeFile(new URL(filename, artifacts), JSON.stringify(release, null, 2) + '\n')
console.log(JSON.stringify(release))
